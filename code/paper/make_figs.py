#!/usr/bin/env python3
"""Write figs/results.tex (pgfplots) and figs/table.tex from the graded record only.

    python make_figs.py GRADED_DIR

GRADED_DIR holds rov-unit-<T0>.json for the eight graded days. Each
curve is the mean over days with min-max whiskers. No number in the
figure is typed by hand.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

DAILY = [1, 2, 4, 8, 15, 30]
SUB = [("1h", 1 / 24), ("6h", 6 / 24), ("1d", 1.0)]


FLOOR = 1e-5   # percent; the log axis starts here, a zero day's whisker runs to it


def series(units: list[dict], arm: str, keys, metric: str) -> list[tuple]:
    """(x, mean, down, up) in percent. A point whose mean is zero cannot
    sit on a log axis, so it is left out and reported on stderr."""
    out = []
    for label, x in keys:
        vals = [u[arm][label][metric] * 100 for u in units]   # percent
        m = sum(vals) / len(vals)
        if m <= 0:
            print(f"omitted from figure: {arm} {label} {metric} mean is 0",
                  file=sys.stderr)
            continue
        out.append((x, m, m - max(min(vals), FLOOR), max(vals) - m))
    return out


def mean_se(vals: list[float]) -> tuple[float, float]:
    k = len(vals)
    m = sum(vals) / k
    var = sum((v - m) ** 2 for v in vals) / (k - 1)
    return m, (var / k) ** 0.5


def cell(vals: list[float]) -> str:
    m, se = mean_se([v * 100 for v in vals])
    return f"{sig(m, 3)} ({sig(se, 2)})"


def sig(x: float, n: int) -> str:
    """n significant figures in fixed point (values span 1e-5 to 1 percent,
    and exponent notation reads badly in a table)."""
    if x == 0:
        return "0"
    return f"{x:.{max(n - 1 - math.floor(math.log10(abs(x))), 0)}f}"


def table(units: list[dict]) -> str:
    """Means over days with the standard error over days, in percent of
    announcements, for both arms. The split columns are shares of the
    wrong accepts, pooled over days."""
    rows = []
    for arm, labels in (("daily", [str(d) for d in DAILY]),
                        ("subday", [s for s, _ in SUB])):
        for lab in labels:
            r = [u[arm][lab] for u in units]
            acc = sum(x["accept"] for x in r)
            rev = sum(x["accept_revoked"] for x in r)
            peer = [x["weighted"]["accept_peer"] / x["weighted"]["peer_total"]
                    for x in r]
            name = f"{lab} d" if arm == "daily" else lab
            rows.append(
                f"{name} & {cell([x['e_accept'] for x in r])} & "
                f"{100 * rev / acc if acc else 0:.0f} & "
                f"{cell(peer)} & {cell([x['e_drop'] for x in r])} \\\\")
        rows.append(r"\midrule")
    rows.pop()
    return ("% generated by make_figs.py from the graded unit records\n"
            r"\begin{tabular}{@{}lrrrr@{}}" "\n" r"\toprule" "\n"
            r"age & wrong accepts & removed & peer-weighted & wrong drops \\" "\n"
            r"    & \% (SE)       & \% of accepts & \% (SE) & \% (SE) \\" "\n"
            r"\midrule" "\n" + "\n".join(rows) + "\n"
            r"\bottomrule" "\n" r"\end{tabular}" "\n")


def coords(pts: list[tuple]) -> str:
    return " ".join(f"({x:g},{m:.6g}) -= (0,{lo:.6g}) += (0,{hi:.6g})"
                    for x, m, lo, hi in pts)


def main(graded: Path) -> int:
    units = [json.loads(p.read_text()) for p in sorted(graded.glob("rov-unit-*.json"))]
    if len(units) != 8 or any(u.get("shakedown") for u in units):
        raise SystemExit("need exactly the eight graded unit records")
    daily = [(str(d), d) for d in DAILY]
    acc = series(units, "daily", daily, "e_accept")
    drp = series(units, "daily", daily, "e_drop")
    sacc = series(units, "subday", SUB, "e_accept")
    sdrp = series(units, "subday", SUB, "e_drop")
    plot = rf"""% generated by make_figs.py from {len(units)} graded unit records
\begin{{tikzpicture}}
\begin{{axis}}[width=\columnwidth, height=58mm, xmode=log, ymode=log, ymin={FLOOR:g},
  xlabel={{age of the relying party's list (days)}},
  ylabel={{share of announcements (\%)}},
  xtick={{0.0417,0.25,1,2,4,8,15,30}},
  xticklabels={{1h,6h,1,2,4,8,15,30}},
  legend pos=south east, legend style={{font=\scriptsize, fill=white}},
  error bars/y dir=both, error bars/y explicit]
\addplot[mark=*, black, mark options={{fill=black}}] coordinates {{{coords(acc)}}};
\addlegendentry{{wrong accepts, daily archive}}
\addplot[mark=square*, black, dashed, mark options={{solid, fill=black}}] coordinates {{{coords(drp)}}};
\addlegendentry{{wrong drops, daily archive}}
\addplot[mark=o, gray, mark options={{fill=white}}] coordinates {{{coords(sacc)}}};
\addlegendentry{{wrong accepts, 20-min snapshots}}
\addplot[mark=square, gray, dashed, mark options={{solid, fill=white}}] coordinates {{{coords(sdrp)}}};
\addlegendentry{{wrong drops, 20-min snapshots}}
\end{{axis}}
\end{{tikzpicture}}
"""
    out = Path(__file__).resolve().parent / "figs"
    out.mkdir(exist_ok=True)
    (out / "results.tex").write_text(plot)
    (out / "table.tex").write_text(table(units))
    print(f"-> {out / 'results.tex'}, {out / 'table.tex'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1])))
