"""The sealed-run discipline as a harness.

Extracted from the hand-rolled copies in every audit cell after two
instrument deaths came from exactly the parts a harness standardizes:

- **seal guards** — code that refuses to run against an unsealed
  prereg (written four times: OT-13..18, XPROTO-BMP/OSPF);
- **single-source schedules** — one event list rendering both the
  executable script and the evaluator's nominal model (the BMP-V1
  evaluator mis-VOIDed MC1 because its hand-derived nominals forgot
  a `sleep`; `gen_schedule.py` was the fix, this is its home);
- **interval fidelity checks** — per-interval, never cumulative
  (sequential sleeps drift);
- **as-executed records** — result JSON with the version pins the
  readscope-integration note makes non-negotiable.

Forward-only: sealed runners already on the record keep their
hand-rolled machinery byte-frozen.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from dataclasses import dataclass
from datetime import date
from pathlib import Path


class UnsealedPreregError(RuntimeError):
    pass


class CoolingOffError(RuntimeError):
    """The structural form of the rate-limit rule: no override path
    exists. A safety mechanism the hypothesis author can wave off is
    an advisory, not a mechanism (reviewer finding, 2026-08-17; the
    program's own ledger of seven recorded owner overrides is the
    evidence)."""


_DATE_RE = re.compile(r"(\d{4}-\d{2}-\d{2})")


def require_seal(
    prereg_path: str | Path,
    *,
    min_cooling_days: int = 1,
) -> None:
    """Refuse to proceed unless the prereg is SEALED — and, for
    preregs that declare their construction date, unless the cooling
    interval has structurally expired.

    Contract (forward-only; already-sealed artifacts keep their
    frozen runners): the file must contain ``STATUS: SEALED`` and not
    ``STATUS: DRAFT-UNSEALED``; and a new prereg MUST carry a line
    ``FAMILY-CONSTRUCTED: YYYY-MM-DD``. When that marker is present,
    the first date on the STATUS line must be at least
    ``min_cooling_days`` later — **there is no override parameter,
    deliberately**. Old preregs without the marker pass the seal
    check only (their seals are history; their overrides are in the
    ledger).
    """
    text = Path(prereg_path).read_text(encoding="utf-8")
    name = Path(prereg_path).name
    if "STATUS: DRAFT-UNSEALED" in text or "STATUS: SEALED" not in text:
        raise UnsealedPreregError(
            f"REFUSED: {name} is not SEALED. "
            "No run may execute before a dated seal declaration."
        )
    marker = re.search(r"FAMILY-CONSTRUCTED:\s*(\d{4}-\d{2}-\d{2})",
                       text)
    if marker is None:
        return
    constructed = date.fromisoformat(marker.group(1))
    status_idx = text.index("STATUS: SEALED")
    sealed_m = _DATE_RE.search(text, status_idx)
    if sealed_m is None:
        raise CoolingOffError(
            f"REFUSED: {name} declares FAMILY-CONSTRUCTED but its "
            "STATUS line carries no seal date to check against."
        )
    sealed = date.fromisoformat(sealed_m.group(1))
    if (sealed - constructed).days < min_cooling_days:
        raise CoolingOffError(
            f"REFUSED: {name} sealed {sealed} against a family "
            f"constructed {constructed} — inside the "
            f"{min_cooling_days}-day cooling interval. This check has "
            "no override path."
        )


@dataclass
class ScheduleEvent:
    """One stamped step: an optional shell action, then a sleep."""

    label: str
    sleep_after_s: float
    action: str | None = None


class Schedule:
    """A sealed flap/measurement schedule, single-sourced.

    One event list renders BOTH the executable bash script (epoch
    stamps to stdout, which become the execution record) and the
    nominal model the evaluator checks stamps against. They cannot
    disagree because they do not exist separately.
    """

    def __init__(self, events: list[ScheduleEvent]):
        if not events:
            raise ValueError("empty schedule")
        self.events = events

    def render_script(self) -> str:
        lines = [
            "#!/bin/bash",
            "# GENERATED by governor.sealed.Schedule -- edit the",
            "# generator, not this file.",
            "set -u",
            'stamp() { echo "$(date -u +%s.%6N) $1"; }',
        ]
        for ev in self.events:
            lines.append(f'stamp "{ev.label}"')
            if ev.action:
                lines.append(ev.action)
            if ev.sleep_after_s:
                lines.append(f"sleep {ev.sleep_after_s:g}")
        return "\n".join(lines) + "\n"

    def nominals(self) -> list[dict]:
        return [
            {"label": ev.label, "sleep_after": ev.sleep_after_s}
            for ev in self.events
        ]

    def write(self, script_path: str | Path,
              nominals_path: str | Path) -> None:
        Path(script_path).write_text(self.render_script(),
                                     encoding="utf-8", newline="\n")
        Path(nominals_path).write_text(
            json.dumps({"generator": "governor.sealed.Schedule",
                        "events": self.nominals()}, indent=1),
            encoding="utf-8")

    def total_nominal_s(self) -> float:
        return sum(ev.sleep_after_s for ev in self.events)


def load_stamps(path: str | Path) -> list[tuple[float, str]]:
    stamps = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        t, _, label = line.strip().partition(" ")
        stamps.append((float(t), label))
    return stamps


def check_intervals(
    stamps: list[tuple[float, str]],
    nominals: list[dict],
    *,
    tol_s: float = 3.0,
) -> list[str]:
    """Per-interval fidelity against the generated nominals.

    Returns violation strings (empty = MC passes). Per-interval, not
    cumulative: sequential sleeps drift and an absolute check would
    punish a faithful run.
    """
    if len(nominals) != len(stamps):
        return [f"stamp count {len(stamps)} vs nominal {len(nominals)}"]
    viol = []
    for i, ((t0, l0), (t1, _)) in enumerate(zip(stamps, stamps[1:])):
        if nominals[i]["label"] != l0:
            viol.append(f"label mismatch at {i}: {l0!r} vs "
                        f"{nominals[i]['label']!r}")
            continue
        n = nominals[i]["sleep_after"]
        if abs((t1 - t0) - n) > tol_s:
            viol.append(f"{l0}: {t1 - t0:.2f}s vs {n:g}s")
    return viol


def version_pins() -> dict:
    """The pins an as-executed record must carry."""
    pins = {"python": sys.version.split()[0]}
    for pkg in ("numpy", "readscope"):
        try:
            mod = __import__(pkg)
            pins[pkg] = getattr(mod, "__version__", "unknown")
        except ImportError:
            pins[pkg] = "absent"
    try:
        pins["git_commit"] = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, timeout=10,
            cwd=Path(__file__).parent,
        ).stdout.strip() or "unknown"
    except Exception:
        pins["git_commit"] = "unknown"
    return pins


def write_record(path: str | Path, payload: dict) -> None:
    """As-executed result record, version-pinned. The payload is the
    runner's; the pins are appended under ``_pins`` and a pre-existing
    file is never silently overwritten (as-executed means once)."""
    p = Path(path)
    if p.exists():
        raise FileExistsError(
            f"{p} already exists; as-executed records are written once"
        )
    payload = dict(payload)
    payload["_pins"] = version_pins()
    p.write_text(json.dumps(payload, indent=1), encoding="utf-8")
